//! Putting a .fw update package into a factory image, for first boot to install.
//!
//! A .fw is not a partition image: it is a gzip'd tar the device installs by
//! running its `./update` as root, and there is no OS in maskrom to run it. So,
//! as the browser flasher's `inject.js` does:
//!
//! 1. the package bytes go into the unused tail of the rootfs PARTITION —
//!    parameter.txt gives rootfs 3.5 GiB and rootfs.img is 2.235 GiB, and
//!    nothing ever touches the gap;
//! 2. a one-shot systemd unit goes into the ext2 rootfs. On first boot it reads
//!    those bytes back off the disk and hands them to the stock updater,
//!    exactly as the vendor's own network path does.
//!
//! The script below is the page's, byte for byte. Two device behaviours shape
//! it: `birddog-update-wrapper` stops BirdDogRunner and never restarts it, so
//! the script reboots rather than leaving a dark HDMI output that looks
//! bricked; and the done-marker is written BEFORE the update runs, so a package
//! that panics the box is not reinstalled on every boot.

use super::ext2::{Ext2, Patch};
use super::source::Source;
use std::sync::Arc;

pub const PAYLOAD_ALIGN_SECTORS: u64 = 2048; // 1 MiB
const SECTOR_SIZE: u64 = 512;

const UNIT_PATH: &str = "/etc/systemd/system";
const UNIT_NAME: &str = "BirdDogInject.service";
const SCRIPT_DIR: &str = "/usr/local/bin";
const SCRIPT_NAME: &str = "bd-inject.sh";
const WANTS_DIR: &str = "/etc/systemd/system/multi-user.target.wants";
const MARKER: &str = "/userdata/.bd-inject-done";

const SCRIPT: &str = r#"#!/bin/sh
# Generated by birddog-play-flasher. Applies a .fw package that was written
# into the unused tail of the rootfs partition when this image was flashed.
MARK=@MARK@
LOG=/userdata/bd-inject.log
SKIP=@SKIP@
COUNT=@COUNT@
BYTES=@BYTES@
PKG=/tmp/bd-inject.fw

[ -f "$MARK" ] && exit 0
exec >>"$LOG" 2>&1
echo "=== bd-inject $(date) ==="

# The partition device, not the whole disk: the offset is partition-relative, so
# it stays correct however the eMMC and any SD card end up numbered.
part=$(awk '$2 == "/" && $1 ~ /^\/dev\// {print $1; exit}' /proc/mounts)
[ -z "$part" ] && part=$(readlink -f /dev/root 2>/dev/null)
if [ -z "$part" ] || [ ! -b "$part" ]; then
  echo "cannot find the root partition device; giving up"
  exit 1
fi
echo "root partition: $part"

dd if="$part" bs=512 skip=$SKIP count=$COUNT 2>/dev/null | head -c $BYTES > "$PKG"
size=$(wc -c < "$PKG")
if [ "$size" != "$BYTES" ]; then
  echo "short read: got $size of $BYTES bytes"
  exit 1
fi
# A .fw is gzip; if the first two bytes are not 1f 8b the payload is not there.
magic=$(dd if="$PKG" bs=1 count=2 2>/dev/null | od -An -tx1 | tr -d ' \n')
if [ "$magic" != "1f8b" ]; then
  echo "payload is not a gzip stream (magic $magic); giving up"
  exit 1
fi

# Before installing, not after: a package that kills the box must not be
# reinstalled on every subsequent boot.
touch "$MARK"

echo "handing $PKG to the stock updater"
echo "$PKG" > /tmp/birddog-update-package
: > /tmp/birddog-update-lock
systemctl start BirdDogUpdateRunner

# birddog-update-wrapper clears the lock on the way out, whatever the outcome.
i=0
while [ -f /tmp/birddog-update-lock ] && [ $i -lt 900 ]; do
  sleep 2
  i=$((i + 1))
done
echo "updater finished after $((i * 2))s"

# The wrapper stops BirdDogRunner and only ever restarts it by rebooting.
# Exiting here would leave the device with no video output, looking bricked.
sync
reboot
"#;

pub fn inject_script(sector: u64, bytes: u64) -> String {
    SCRIPT
        .replace("@MARK@", MARKER)
        .replace("@SKIP@", &sector.to_string())
        .replace("@COUNT@", &bytes.div_ceil(SECTOR_SIZE).to_string())
        .replace("@BYTES@", &bytes.to_string())
}

pub fn inject_unit() -> String {
    format!(
        "[Unit]
Description=BirdDog PLAY injected firmware package
After=multi-user.target
RequiresMountsFor=/userdata
ConditionPathExists=!/userdata/.bd-inject-done

[Service]
Type=oneshot
ExecStart={SCRIPT_DIR}/{SCRIPT_NAME}

[Install]
WantedBy=multi-user.target
"
    )
}

#[derive(Debug, Clone)]
pub struct Injection {
    /// Where the package goes, in sectors from the start of rootfs.
    pub relative_sector: u64,
    pub payload_sectors: u64,
    pub spare_sectors: u64,
    pub fs_sectors: u64,
    pub patches: Vec<Patch>,
}

/// Work out where the package goes and what changes in the filesystem.
pub fn plan(rootfs: Arc<dyn Source>, rootfs_sectors: u64, payload_bytes: u64, now: u32) -> Result<Injection, String> {
    let image_len = rootfs.len();
    let mut fs = Ext2::open(rootfs, now)?;
    let fs_bytes = fs.sb.blocks_count as u64 * fs.sb.block_size as u64;
    let fs_sectors = fs_bytes.div_ceil(SECTOR_SIZE);
    if fs_sectors > image_len / SECTOR_SIZE {
        return Err("the rootfs filesystem claims to be larger than its image".into());
    }
    let relative_sector = fs_sectors.div_ceil(PAYLOAD_ALIGN_SECTORS) * PAYLOAD_ALIGN_SECTORS;
    let payload_sectors = payload_bytes.div_ceil(SECTOR_SIZE);
    let spare = rootfs_sectors.saturating_sub(relative_sector);
    if payload_sectors > spare {
        return Err(format!(
            "the package needs {payload_sectors} sectors but only {spare} are free after the filesystem"
        ));
    }
    let script = inject_script(relative_sector, payload_bytes);
    fs.create_file(SCRIPT_DIR, SCRIPT_NAME, script.as_bytes(), 0o755)?;
    fs.create_file(UNIT_PATH, UNIT_NAME, inject_unit().as_bytes(), 0o644)?;
    fs.create_symlink(WANTS_DIR, UNIT_NAME, &format!("{UNIT_PATH}/{UNIT_NAME}"))?;
    fs.flush_metadata()?;
    Ok(Injection {
        relative_sector,
        payload_sectors,
        spare_sectors: spare,
        fs_sectors,
        patches: fs.patches(),
    })
}
